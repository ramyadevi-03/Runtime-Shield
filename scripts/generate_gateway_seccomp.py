#!/usr/bin/env python3
"""Regenerate ``gateway-seccomp.json`` from Docker's default seccomp profile.

The gateway runs as a non-root user with ``cap_drop: ALL`` and
``no-new-privileges``. That is the right posture, but Docker's default profile
then blocks the syscalls bubblewrap needs to build its mount view inside the
user namespace it creates. This script applies the minimum documented
relaxations and writes the profile consumed by ``docker-compose.yml``.

Usage:
    python scripts/generate_gateway_seccomp.py \
        --default-profile /path/to/docker/default.json \
        --output gateway-seccomp.json

    # CI / verification: regenerate in memory and compare semantics.
    python scripts/generate_gateway_seccomp.py --check \
        --default-profile /path/to/docker/default.json

The pinned default profile used for the committed file is moby v28.3.3:
https://raw.githubusercontent.com/moby/moby/v28.3.3/profiles/seccomp/default.json

The relaxations are unconditional ``SCMP_ACT_ALLOW`` entries. The kernel still
enforces namespace ownership and capability checks, so they do not grant a
process capabilities it did not already have.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from pathlib import Path

PINNED_DEFAULT_PROFILE = (
    "https://raw.githubusercontent.com/moby/moby/v28.3.3/"
    "profiles/seccomp/default.json"
)

BWRAP_MOUNT_COMMENT = (
    "gateway patch: bubblewrap builds its mount view inside the user namespace "
    "it just created; the kernel denies all of these without CAP_SYS_ADMIN "
    "over the owning namespace."
)
BWRAP_NEW_MOUNT_API_COMMENT = (
    "gateway patch: new mount API used by bubblewrap >= 0.11 inside its own "
    "user namespace; kernel-gated like mount()."
)
BWRAP_UNSHARE_COMMENT = (
    "gateway patch: bubblewrap creates an unprivileged user namespace "
    "(kernel.unprivileged_userns_clone / AppArmor still govern on the host)."
)
BWRAP_CHROOT_COMMENT = (
    "gateway patch: chroot is CAP_SYS_CHROOT-gated in the default profile; "
    "cap_drop ALL would bake in a denial and break bubblewrap. The kernel "
    "still requires the capability over the owning namespace."
)
CLONE_COMMENT = (
    "gateway patch: exact-match clone rule permitting the bubblewrap namespace "
    "combination used by the nested sandbox; all other namespace combinations "
    "stay blocked."
)
CLONE_S390_COMMENT = "s390 parameter ordering for clone is different"

# clone() namespace-flag combinations that bubblewrap requests: NEWUSER,
# NEWUSER|NEWNS, NEWUSER|NEWIPC, NEWUSER|NEWIPC|NEWNS, NEWUSER|NEWPID|NEWIPC|
# NEWNS, NEWUSER|NEWPID|NEWNET|NEWIPC|NEWNS, and the NEWCGROUP variant.
CLONE_NAMESPACE_COMBINATIONS = (
    268435456,   # 0x10000000 CLONE_NEWUSER
    268566528,   # 0x10020000 CLONE_NEWUSER|CLONE_NEWNS
    402653184,   # 0x18000000 CLONE_NEWUSER|CLONE_NEWIPC
    402784256,   # 0x18020000 CLONE_NEWUSER|CLONE_NEWIPC|CLONE_NEWNS
    939655168,   # 0x38020000 CLONE_NEWUSER|CLONE_NEWPID|CLONE_NEWIPC|CLONE_NEWNS
    1476526080,  # 0x58020000 ...|CLONE_NEWNET
    2013396992,  # 0x78020000 ...|CLONE_NEWCGROUP
)

NEW_MOUNT_API_SYSCALLS = (
    "fsopen",
    "fsmount",
    "fspick",
    "open_tree",
    "move_mount",
    "mount_setattr",
)

PROFILE_COMMENT = (
    "gateway-seccomp.json: Docker default seccomp profile (moby v28.3.3) with "
    "minimal relaxations to allow the nested bubblewrap sandbox inside the "
    "hardened gateway container (non-root user, cap_drop ALL, "
    "no-new-privileges). Changes: unshare/mount/umount2/pivot_root/new-mount-"
    "API/chroot allowed unconditionally (the kernel still enforces namespace "
    "ownership and capability checks), and exact-match clone() rules added "
    "for the namespace combinations bubblewrap requests. Generated by "
    "scripts/generate_gateway_seccomp.py."
)


def _entry_names(entry: dict) -> list[str]:
    names = entry.get("names")
    return names if isinstance(names, list) else []


def _find_entry(profile: dict, name: str) -> dict | None:
    for entry in profile.get("syscalls", []):
        if name in _entry_names(entry):
            return entry
    return None


def _set_comment(profile: dict, name: str, comment: str) -> None:
    entry = _find_entry(profile, name)
    if entry is not None:
        entry["comment"] = comment


def _ensure_allowed(profile: dict, names: tuple[str, ...], comment: str) -> None:
    """Ensure every syscall is allowed, grouping missing names together."""
    missing = [name for name in names if _find_entry(profile, name) is None]
    if missing:
        profile.setdefault("syscalls", []).append({
            "names": missing,
            "action": "SCMP_ACT_ALLOW",
            "comment": comment,
        })
    for name in names:
        _set_comment(profile, name, comment)


def apply_gateway_patches(profile: dict) -> dict:
    """Apply the documented bubblewrap relaxations to a default profile."""
    profile = json.loads(json.dumps(profile))  # deep copy
    profile.setdefault("defaultAction", "SCMP_ACT_ERRNO")
    profile.setdefault("defaultErrnoRet", 1)

    _ensure_allowed(
        profile,
        ("mount", "umount2", "pivot_root"),
        BWRAP_MOUNT_COMMENT,
    )
    _ensure_allowed(profile, NEW_MOUNT_API_SYSCALLS, BWRAP_NEW_MOUNT_API_COMMENT)
    _ensure_allowed(profile, ("unshare",), BWRAP_UNSHARE_COMMENT)
    _ensure_allowed(profile, ("chroot",), BWRAP_CHROOT_COMMENT)

    clone_entries = list(profile.get("syscalls", []))
    for value_two in CLONE_NAMESPACE_COMBINATIONS:
        for index, comment in ((0, CLONE_COMMENT), (1, CLONE_S390_COMMENT)):
            clone_entries.append({
                "names": ["clone"],
                "action": "SCMP_ACT_ALLOW",
                "args": [{
                    "index": index,
                    "value": 2114060288,
                    "valueTwo": value_two,
                    "op": "SCMP_CMP_MASKED_EQ",
                }],
                "comment": comment,
            })
    profile["syscalls"] = clone_entries

    ordered = {"_comment": PROFILE_COMMENT}
    ordered.update(profile)
    return ordered


def load_profile(source: str) -> dict:
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source, timeout=30) as response:
            return json.load(response)
    return json.loads(Path(source).read_text(encoding="utf-8"))


def normalized_rules(profile: dict) -> set[tuple]:
    """Functional rule set: grouping and comments do not affect enforcement."""
    rules = set()
    for entry in profile.get("syscalls", []):
        action = entry.get("action")
        args = json.dumps(entry.get("args"), sort_keys=True, separators=(",", ":"))
        for name in _entry_names(entry):
            rules.add((name, action, args))
    return rules


def compare_profiles(generated: dict, existing: dict) -> list[str]:
    problems = []
    for key in ("defaultAction", "defaultErrnoRet", "archMap"):
        if generated.get(key) != existing.get(key):
            problems.append(f"{key} differs")
    generated_rules = normalized_rules(generated)
    existing_rules = normalized_rules(existing)
    missing = sorted(existing_rules - generated_rules)
    extra = sorted(generated_rules - existing_rules)
    if missing:
        problems.append(f"missing rules: {missing[:10]}")
    if extra:
        problems.append(f"unexpected rules: {extra[:10]}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--default-profile",
        default=PINNED_DEFAULT_PROFILE,
        help="Docker default seccomp JSON path or URL (pinned moby v28.3.3).",
    )
    parser.add_argument(
        "--output",
        default="gateway-seccomp.json",
        help="Output path for the generated profile.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Compare against --output instead of writing it.",
    )
    args = parser.parse_args(argv)

    generated = apply_gateway_patches(load_profile(args.default_profile))
    if args.check:
        existing = json.loads(Path(args.output).read_text(encoding="utf-8"))
        problems = compare_profiles(generated, existing)
        if problems:
            print("gateway-seccomp.json is out of date:", file=sys.stderr)
            for problem in problems:
                print(f"  - {problem}", file=sys.stderr)
            return 1
        print("gateway-seccomp.json matches the generator.")
        return 0

    Path(args.output).write_text(
        json.dumps(generated, indent=2) + "\n", encoding="utf-8"
    )
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
